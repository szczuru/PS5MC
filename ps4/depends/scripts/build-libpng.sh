#!/bin/bash
set -euo pipefail
source "$(dirname "$0")/env-depends.sh"

"$ROOT/depends/scripts/build-zlib.sh"

VER=1.6.43
SRC="$PS4_BUILD/libpng-$VER"
TARBALL="libpng-$VER.tar.xz"

if [ -f "$PS4_PREFIX/lib/libpng16.a" ] || [ -f "$PS4_PREFIX/lib/libpng.a" ]; then
  echo "libpng already built"
  exit 0
fi

cd "$PS4_BUILD"
if [ ! -d "$SRC" ]; then
  echo "Downloading libpng $VER ..."
  curl -fL --retry 3 -o "$TARBALL" \
    "https://downloads.sourceforge.net/project/libpng/libpng16/${VER}/libpng-${VER}.tar.xz"
  tar xf "$TARBALL"
fi

cd "$SRC"

# Hand-built static lib – avoid broken cross configure
# Core sources for libpng 1.6
OBJS="png.o pngerror.o pngget.o pngmem.o pngpread.o pngread.o pngrio.o pngrtran.o pngrutil.o pngset.o pngtrans.o pngwio.o pngwrite.o pngwtran.o pngwutil.o"

cat > Makefile.ps4 << MAKE
CC = $CC
CFLAGS = $CFLAGS -I. -I$PS4_PREFIX/include -DPNG_ARM_NEON_OPT=0 -DPNG_INTEL_SSE_OPT=0
AR = $AR
RANLIB = $RANLIB

OBJS = $OBJS

all: libpng16.a

libpng16.a: \$(OBJS)
	\$(AR) rcs \$@ \$(OBJS)
	\$(RANLIB) \$@

%.o: %.c
	\$(CC) \$(CFLAGS) -c -o \$@ \$<

clean:
	rm -f \$(OBJS) libpng16.a
MAKE

# pnglibconf.h is generated by configure; ship a minimal one if missing
if [ ! -f pnglibconf.h ]; then
  if [ -f scripts/pnglibconf.h.prebuilt ]; then
    cp scripts/pnglibconf.h.prebuilt pnglibconf.h
  else
    # very minimal fallback
    cat > pnglibconf.h << 'HDR'
#ifndef PNGLCONF_H
#define PNGLCONF_H
#define PNG_LIBPNG_VER_STRING "1.6.43"
#define PNG_LIBPNG_VER_SONUM 16
#define PNG_LIBPNG_VER_DLLNUM 16
#define PNG_LIBPNG_VER_MAJOR 1
#define PNG_LIBPNG_VER_MINOR 6
#define PNG_LIBPNG_VER_RELEASE 43
#define PNG_READ_SUPPORTED
#define PNG_WRITE_SUPPORTED
#define PNG_INFO_IMAGE_SUPPORTED
#define PNG_EASY_ACCESS_SUPPORTED
#define PNG_SET_UNKNOWN_CHUNKS_SUPPORTED
#define PNG_STORE_UNKNOWN_CHUNKS_SUPPORTED
#define PNG_USER_CHUNKS_SUPPORTED
#define PNG_BENIGN_ERRORS_SUPPORTED
#define PNG_FILTER_SUPPORTED
#define PNG_GAMMA_SUPPORTED
#define PNG_READ_GAMMA_SUPPORTED
#endif
HDR
  fi
fi

make -f Makefile.ps4 -j"$(nproc)"

install -d "$PS4_PREFIX/lib" "$PS4_PREFIX/include"
install -m 644 libpng16.a "$PS4_PREFIX/lib/"
ln -sf libpng16.a "$PS4_PREFIX/lib/libpng.a"
install -m 644 png.h pngconf.h pnglibconf.h "$PS4_PREFIX/include/"
echo "libpng OK"
